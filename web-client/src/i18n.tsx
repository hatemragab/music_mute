export type Language = "en" | "ar";
interface I18nValue {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: MessageKey) => string;
  date: (value: string) => string;
  number: (value: number) => string;
}
const Context = createContext<I18nValue | null>(null);
export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Language>(() =>
    localStorage.getItem("musicmute.web.language") === "ar" ? "ar" : "en",
  );
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    localStorage.setItem("musicmute.web.language", lang);
  }, [lang]);
  const value = useMemo<I18nValue>(
    () => ({
      lang,
      setLang,
      t: (key) => (lang === "ar" ? ar[key] : en[key]),
      date: (value) =>
        new Intl.DateTimeFormat(lang, {
          dateStyle: "medium",
          timeStyle: "short",
        }).format(new Date(value)),
      number: (value) => new Intl.NumberFormat(lang).format(value),
    }),
    [lang],
  );
  return <Context.Provider value={value}>{children}</Context.Provider>;
}
export function useI18n() {
  const value = useContext(Context);
  if (!value) throw new Error("I18nProvider required");
  return value;
}

