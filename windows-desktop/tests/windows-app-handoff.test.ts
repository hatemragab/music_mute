import { expect, it } from "vitest";
import { parseWindowsCloudHandoff } from "../src/main/browser/app-handoff.js";
import { cloudHandoffUrl } from "../../chrome-extension/src/shared/app-handoff.js";
it("accepts the same token-free public URI generated by the shared Chrome extension", () => {
  expect(
    parseWindowsCloudHandoff(cloudHandoffUrl("bZxrIoCPsOc", 60.2)),
  ).toEqual({ videoId: "bZxrIoCPsOc", durationSeconds: 61 });
  expect(parseWindowsCloudHandoff(cloudHandoffUrl("bZxrIoCPsOc"))).toEqual({
    videoId: "bZxrIoCPsOc",
  });
});
it.each([
  "https://example.test/cloud?video_id=bZxrIoCPsOc",
  "musicmute-local://cloud?video_id=bZxrIoCPsOc&id_token=secret",
  "musicmute-local://cloud?video_id=bZxrIoCPsOc&rights_confirmed=true",
  "musicmute-local://cloud?video_id=bZxrIoCPsOc&video_id=evil",
  "musicmute-local://cloud?video_id=bZxrIoCPsOc&duration_seconds=1201",
  "musicmute-local://user:password@cloud?video_id=bZxrIoCPsOc",
  "musicmute-local://cloud/private?video_id=bZxrIoCPsOc",
  "musicmute-local://setup?execute=cmd",
])("refuses non-public handoff %s", (value) =>
  expect(parseWindowsCloudHandoff(value)).toBeNull(),
);
