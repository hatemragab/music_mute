export function isKnownDiagnosticCode(value: unknown): value is string {
  return typeof value === "string" && CODES.has(value);
}
export function projectDiagnosticCode(value: unknown): string {
  return isKnownDiagnosticCode(value) ? value : "UNKNOWN_ERROR";
}
